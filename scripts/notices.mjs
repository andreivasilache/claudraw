// Regenerate THIRD_PARTY_NOTICES.md: the licenses of everything that is bundled into dist/ (the browser UI).
// Run after changing the UI dependencies: npm run notices
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const ROOTS = ['@excalidraw/excalidraw', '@dagrejs/dagre', 'elkjs', '@xterm/xterm', '@xterm/addon-fit', '@xterm/addon-web-links', 'react', 'react-dom']

const readPkg = (dir) => JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'))
/** Node resolution: look in dir/node_modules, then in the parents' node_modules. */
const find = (name, from) => {
  for (let d = from; ; d = dirname(d)) {
    const p = join(d, 'node_modules', name)
    if (existsSync(join(p, 'package.json'))) return p
    if (dirname(d) === d) return null
  }
}

const seen = new Map()
const visit = (dir) => {
  const pkg = readPkg(dir)
  if (seen.has(dir)) return
  seen.set(dir, pkg)
  for (const dep of Object.keys(pkg.dependencies ?? {}).concat(Object.keys(pkg.optionalDependencies ?? {}))) {
    const d = find(dep, dir)
    if (d) visit(d)
  }
}
for (const r of ROOTS) visit(find(r, root))

const licenseOf = (pkg) => (typeof pkg.license === 'string' ? pkg.license : pkg.license?.type ?? pkg.licenses?.map((l) => l.type).join(' OR ') ?? 'UNKNOWN')
const textOf = (dir) => {
  const f = readdirSync(dir).find((n) => /^(licen[sc]e|copying)(\.|$)/i.test(n))
  return f ? readFileSync(join(dir, f), 'utf8').replace(/\r\n/g, '\n').trim() : ''
}

// Group packages that carry the same license text, so each text is printed once.
const groups = new Map()
for (const [dir, pkg] of [...seen].sort((a, b) => a[1].name.localeCompare(b[1].name))) {
  const text = textOf(dir)
  const key = text.replace(/^.*copyright.*$/gim, '').replace(/\s+/g, ' ').trim() || `SPDX:${licenseOf(pkg)}`
  const g = groups.get(key) ?? { text, spdx: licenseOf(pkg), pkgs: [] }
  const holder = text.split('\n').find((l) => /copyright/i.test(l))?.trim()
  g.pkgs.push({ name: pkg.name, version: pkg.version, holder })
  groups.set(key, g)
}

let out = readFileSync(join(root, 'scripts/notices.head.md'), 'utf8').trimEnd() + '\n\n'
out += '## npm packages bundled into the UI (`dist/`)\n\n'
out += `Generated by \`npm run notices\` from the dependency tree of ${ROOTS.map((r) => `\`${r}\``).join(', ')}. ${seen.size} packages.\n\n`
for (const g of [...groups.values()].sort((a, b) => b.pkgs.length - a.pkgs.length)) {
  out += `### ${g.spdx} (${g.pkgs.length})\n\n`
  out += g.pkgs.map((p) => `- ${p.name}@${p.version}${p.holder ? ` — ${p.holder}` : ''}`).join('\n') + '\n\n'
  if (g.text) out += '```text\n' + g.text + '\n```\n\n'
  else out += `_No license file in these packages; the license is declared in package.json as ${g.spdx}._\n\n`
}
writeFileSync(join(root, 'THIRD_PARTY_NOTICES.md'), out)
console.log(`THIRD_PARTY_NOTICES.md: ${seen.size} packages, ${groups.size} license texts`)
